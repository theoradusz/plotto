"""Write src/metrics.js: the advance widths of the printable ASCII characters of each theme font.

plotto lays out titles, labels and legends with these widths. The same table runs in Node and in
the browser, so both draw the same SVG. Run it again only if a theme font changes:

    python scripts/font_metrics.py
"""

import json
from pathlib import Path

from fontTools.ttLib import TTFont

HOME = Path.home()
FONTS = {
    # Arial: metric-compatible with Helvetica and Liberation Sans (the neutral font stack).
    "arial": ("/System/Library/Fonts/Supplemental/Arial.ttf", "/System/Library/Fonts/Supplemental/Arial Bold.ttf"),
    "mplus": (HOME / "Library/Fonts/MPLUS1p-Regular.ttf", HOME / "Library/Fonts/MPLUS1p-Bold.ttf"),
}


def widths(path):
    font = TTFont(path)
    em = font["head"].unitsPerEm
    cmap, hmtx = font.getBestCmap(), font["hmtx"]
    return [round(hmtx[cmap[c]][0] / em, 3) for c in range(32, 127)]


table = {name: {"regular": widths(regular), "bold": widths(bold)} for name, (regular, bold) in FONTS.items()}
out = Path(__file__).parent.parent / "src" / "metrics.js"
out.write_text(
    "// Generated by scripts/font_metrics.py. Advance widths in em of the characters 32-126, per theme font.\n"
    f"export const METRICS = {json.dumps(table)};\n"
)
print(f"wrote {out}")
